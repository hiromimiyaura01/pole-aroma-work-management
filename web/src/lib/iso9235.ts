// 例:"G2.5" → "部位:果実(果皮) / 方法:圧搾(コールドプレス)の精油"
export function describeIso(code: string | null | undefined): string | null {
  if (!code) return null;
  const m = code.trim().match(/^([A-M])(.+)$/);
  if (!m) return null;
  const part = PARTS[m[1]];
  const process = PROCESSES[m[2].trim()];
  if (!part && !process) return null;
  return `部位:${part ?? "不明"} / 方法:${process ?? `区分 ${m[2]}`}`;
}
